/// used by the Quartzite Fitter to validate location assignments.
///
/// Sources
/// - Device totals: Intel "Cyclone V Device Overview" (683694, 2018.05.07), Table 12
///   "Maximum Resource Counts for Cyclone V SX Devices", member C6: 41,910 ALMs, 112 DSP blocks.
///   LAB size: Cyclone V Device Handbook Vol. 1 (CV-5V2, 2016.06.10), "Ten ALMs are in any given LAB".
/// - Quartus' own totals for this exact device (pins 499, LABs 4,191, block memory bits 5,662,720,
///   RAM blocks 553, PLLs 15, DLLs 4, HSSI 9) are copied from the Fitter report Quartus Prime 17.0
///   wrote for the Terasic DE10-Standard golden top (github.com/ffxx283/WM8731_Audio,
///   output_files/DE10_Standard_golden_top.fit.rpt, "Fitter Summary" / "Fitter Resource Usage Summary").
/// - Package pins: the "All Package Pins" table of the same Quartus Fitter report
///   (location, pad number, I/O bank, pin function).
enum CycloneV {
    static let device = "5CSXFC6D6F31C6"
    static let family = "Cyclone V"
    static let package = "FBGA896"

    static let totalALMs = 41_910
    static let totalLABs = 4_191
    static let almsPerLAB = 10
    static let totalPins = 499
    static let totalBlockMemoryBits = 5_662_720
    static let totalRAMBlocks = 553
    static let totalDSPBlocks = 112
    static let totalPLLs = 15
    static let totalDLLs = 4
    static let totalHSSI = 9

    struct PackagePin: Hashable {
        enum Kind: Hashable {
            /// General-purpose I/O usable by FPGA logic (`column` = top/bottom edge, else left/right edge).
            case userIO(column: Bool)
            /// Configuration pin that can become user I/O after configuration (Quartus reserves it by default).
            case dualPurpose
            /// Dedicated configuration, JTAG or HPS pin.
            case dedicated
            /// Power, ground, reference, or no-connect.
            case power
        }
        var location: String      // PIN_AB30
        var bank: String?         // "5B"
        var pad: Int?
        var kind: Kind
        var function: String?     // GND, VCCIO5A, nCSO,DATA4 ...

        var isUserIO: Bool { if case .userIO = kind { return true } else { return false } }
        var ioType: String {
            switch kind {
            case .userIO(let column): return column ? "Column I/O" : "Row I/O"
            case .dualPurpose: return "Dual-purpose configuration pin"
            case .dedicated: return "Dedicated pin"
            case .power: return "Power / reference"
            }
        }
    }

    /// Normalises "ab30", "PIN_AB30", " pin_ab30 " to "PIN_AB30".
    static func normalize(_ location: String) -> String {
        var t = location.trimmingCharacters(in: .whitespaces).uppercased()
        if !t.hasPrefix("PIN_") { t = "PIN_" + t }
        return t
    }

    static func pin(_ location: String?) -> PackagePin? {
        guard let location, !location.trimmingCharacters(in: .whitespaces).isEmpty else { return nil }
        return pins[normalize(location)]
    }

    static let pins: [String: PackagePin] = {
        var d: [String: PackagePin] = [:]
        for line in table.split(separator: "\n") {
            let f = line.split(separator: " ").map(String.init)
            guard f.count >= 4 else { continue }
            let loc = "PIN_" + f[0]
            let bank = f[1] == "-" ? nil : f[1]
            let pad = Int(f[2])
            let kind: PackagePin.Kind
            switch f[3] {
            case "IO": kind = .userIO(column: true)
            case "IOR": kind = .userIO(column: false)
            case "CFG": kind = .dualPurpose
            case "DED": kind = .dedicated
            default: kind = .power
            }
            d[loc] = PackagePin(location: loc, bank: bank, pad: pad, kind: kind, function: f.count > 4 ? f[4] : nil)
        }
        return d
    }()

