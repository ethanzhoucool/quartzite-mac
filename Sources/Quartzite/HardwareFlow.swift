import Foundation

/// The experimental hardware back end: real synthesis, place and route (yosys +
/// nextpnr-mistral) for the Fitter, and an Assembler that wraps the bitstream in a .sof
/// and checks it with an independent decoder (Mistral's mistral-cv) before calling it a
/// success. Used only when the open-source toolchain is installed (see `Toolchain`).
///
/// Nothing here comes from Intel. The .sof is a Quartus-compatible container around a
/// bitstream from the open-source flow; it has not been tested on a DE10-Standard yet.
struct HardwareConfig {
    var toolchain: Toolchain
    /// Folder for `<entity>.sof` (Quartus' output_files).
    var outputDirectory: URL
    /// Where the .sof goes (default `outputDirectory/<entity>.sof`).
    var sofURL: URL? = nil
    /// Intermediate files (Verilog, .qsf, netlists, logs, .rbf, decoded bitstreams).
    var workDirectory: URL? = nil
    /// .sof record layout: 17 = 11 records as Quartus 17.0-25.1 write them (18.1 included), 16 = 10 records.
    var sofLayout = 17
    var seed = 1
    var device = CycloneV.device
    /// Refuse to overwrite a .sof that Quartzite did not write (for example one from Quartus).
    var protectForeignSOF = true
    var cancel = ProcessCancel()
    /// Called (on a background thread) for each message as it is produced, for live display.
    var onMessage: ((Message) -> Void)? = nil

    func sofFile(_ entity: String) -> URL { sofURL ?? outputDirectory.appendingPathComponent("\(entity).sof") }
    func workDir(_ entity: String) -> URL { workDirectory ?? outputDirectory.appendingPathComponent("quartzite_pnr", isDirectory: true) }
}

/// What the real Fitter produced.
struct PnRResult {
    struct IOCell { var name: String; var pin: String; var bel: String }
    struct Cell { var name: String; var type: String; var bel: String }

    var workDirectory: URL
    var verilogURL: URL
    var qsfURL: URL
    var netlistURL: URL
    var rbfURL: URL
    var btURL: URL
    var yosysLog: URL
    var nextpnrLog: URL
    var yosysVersion: String
    var nextpnrVersion: String
    var mistralVersion: String
    /// yosys `stat`: cell type -> count (MISTRAL_ALUT4, MISTRAL_IB, ...).
    var yosysCells: [(type: String, count: Int)] = []
    /// nextpnr utilization: bel type -> (used, available).
    var utilization: [(type: String, used: Int, available: Int)] = []
    var ioCells: [IOCell] = []
    var cells: [Cell] = []
    var rbfBytes = 0
    /// Decoded from nextpnr's .rbf by mistral-cv.
    var check: BitstreamCheck
    var times: [(step: String, seconds: TimeInterval)] = []

    var almsUsed: Int { check.configuredALMs }
    var labsUsed: Int { check.configuredLABs }
    func used(_ type: String) -> (used: Int, available: Int)? { utilization.first { $0.type == type }.map { ($0.used, $0.available) } }
}

/// What the Assembler produced.
struct AssemblyResult {
    var sofURL: URL
    var bytes: Int
    var checksum: UInt32
    var crc: UInt16
    var records: Int
    var layout: Int
    var compilerVersionRecord: String
    var extractedRBF: URL
    var btURL: URL
    /// The CRAM and PRAM re-extracted from the written .sof equal nextpnr's bitstream bit for bit.
    var roundTripIdentical: Bool
    var check: BitstreamCheck
    var failure: String?
    var passed: Bool { failure == nil && check.passed && roundTripIdentical }

    var checksumText: String { HardwareFlow.hex32(checksum) }
}

enum HardwareFlow {
    static let experimentalNotice = "EXPERIMENTAL: this .sof was generated by Quartzite with the open-source Mistral/nextpnr flow, not by Intel Quartus, and it has not yet been tested on hardware. Try it first on a trivial design (for example f = w AND x), and keep compiling in Quartus for graded work."
    static let shortNotice = "Experimental .sof from the open-source Mistral/nextpnr flow (not Quartus); not yet tested on hardware"

    static func hex32(_ v: UInt32) -> String { String(format: "0x%08X", v) }

    struct Failure: Error, LocalizedError {
        var message: String
        var errorDescription: String? { message }
    }

    final class Emitter {
        var messages: [Message] = []
        let forward: ((Message) -> Void)?
        init(_ forward: ((Message) -> Void)?) { self.forward = forward }
        func callAsFunction(_ level: Message.Level, _ text: String, _ children: [Message] = []) {
            let m = Message(level: level, text: text, children: children)
            messages.append(m)
            forward?(m)
        }
    }

    // MARK: - Inputs for the tools

    /// Structural Verilog for yosys: the schematic's gates as Verilog primitives (the same
    /// netlist File > Export Quartus Project writes as `<entity>_backup.v`).
    static func verilog(_ p: Project, circuit: CompiledCircuit) -> String {
        "// Written by Quartzite for the open-source flow (yosys synth_intel_alm + nextpnr-mistral).\n"
            + "// Gate-level netlist of \(p.entityName).bdf.\n"
            + QuartusExport.verilog(p, conn: circuit.conn)
    }

    /// Pin locations for nextpnr: every pin at the location the Quartzite Fitter chose.
    static func qsf(_ p: Project, fit: FitResult) -> String {
        var s = "# Pin locations for nextpnr-mistral, written by Quartzite for \(p.entityName) (\(p.device)).\n"
        s += "# nextpnr reads set_location_assignment; it ignores IO_STANDARD (outputs get its fixed 3.3-V LVTTL-like drive setting).\n"
        for io in fit.io {
            if let b = io.board { s += "# \(io.name) -> \(b.label)\n" } else if !io.assignedByUser { s += "# \(io.name): no location assignment; placed by the Quartzite Fitter\n" }
            s += "set_location_assignment \(io.location) -to \(io.name)\n"
            s += "set_instance_assignment -name IO_STANDARD \"3.3-V LVTTL\" -to \(io.name)\n"
        }
        return s
    }

    /// The bitstream check's spec from the schematic.
    static func spec(_ circuit: CompiledCircuit, fit: FitResult, synthesis: SynthesisResult?) -> BitstreamVerifier.Spec {
        let loc = Dictionary(fit.io.map { ($0.component, $0.location) }, uniquingKeysWith: { a, _ in a })
        return BitstreamVerifier.Spec(
            inputs: circuit.inputs.map { ($0.name, loc[$0.id] ?? "") },
            outputs: circuit.outputs.map { ($0.name, loc[$0.id] ?? "") },
            unusedInputs: Set(synthesis?.unusedInputs ?? []),
            expected: { idx in
                let n = circuit.inputs.count
                return circuit.evaluate((0..<n).map { k in (idx >> (n - 1 - k)) & 1 == 1 }).outputs
            })
    }

    // MARK: - Fitter

    static func placeAndRoute(project p: Project, circuit: CompiledCircuit, synthesis: SynthesisResult, fit: FitResult,
                              config: HardwareConfig, emit: Emitter) throws -> PnRResult {
        let fm = FileManager.default
        let e = p.entityName
        let work = config.workDir(e)
        try fm.createDirectory(at: work, withIntermediateDirectories: true)
        let tc = config.toolchain
        let vURL = work.appendingPathComponent("\(e).v"), qURL = work.appendingPathComponent("\(e).qsf")
        let jURL = work.appendingPathComponent("\(e).json"), rbfURL = work.appendingPathComponent("\(e).rbf")
        let yLog = work.appendingPathComponent("\(e).yosys.log"), nLog = work.appendingPathComponent("\(e).nextpnr.log")
        let repURL = work.appendingPathComponent("\(e).report.json"), routedURL = work.appendingPathComponent("\(e).routed.json")
        let btURL = work.appendingPathComponent("\(e).bt")
        for u in [jURL, rbfURL, yLog, nLog, repURL, routedURL, btURL] { try? fm.removeItem(at: u) }
        try verilog(p, circuit: circuit).write(to: vURL, atomically: true, encoding: .utf8)
        try qsf(p, fit: fit).write(to: qURL, atomically: true, encoding: .utf8)
        let yv = Toolchain.version(of: tc.yosys), nv = Toolchain.version(of: tc.nextpnr), mv = Toolchain.version(of: tc.mistralCV)
        emit(.info, "Using the open-source Cyclone V toolchain (experimental; not the Quartus Fitter)", [
            Message(level: .info, text: "yosys: \(tc.yosys.url.path) (\(yv))"),
            Message(level: .info, text: "nextpnr-mistral: \(tc.nextpnr.url.path) (\(nv))"),
            Message(level: .info, text: "mistral-cv: \(tc.mistralCV.url.path)"),
            Message(level: .info, text: "Work folder: \(work.path)"),
        ])
        var times: [(String, TimeInterval)] = []

        // 1. Synthesis (yosys).
        emit(.info, "Running yosys synth_intel_alm -family cyclonev on \(vURL.lastPathComponent)")
        let script = "read_verilog -sv \(vURL.lastPathComponent); hierarchy -check -top \(e); synth_intel_alm -family cyclonev -top \(e); stat; write_json \(jURL.lastPathComponent)"
        let y = try ToolProcess.run(tc.yosys.url, ["-q", "-l", yLog.lastPathComponent, "-p", script], cwd: work, cancel: config.cancel) { line in
            let t = line.trimmingCharacters(in: .whitespaces)
            if t.hasPrefix("Warning:") { emit(.warning, "yosys: " + t.dropFirst(8).trimmingCharacters(in: .whitespaces)) }
            else if t.hasPrefix("ERROR:") { emit(.error, "yosys: " + t.dropFirst(6).trimmingCharacters(in: .whitespaces)) }
        }
        if y.cancelled { throw Failure(message: "Processing was stopped by the user") }
        times.append(("yosys", y.elapsed))
        guard y.status == 0, fm.fileExists(atPath: jURL.path) else {
            let tail = (try? String(contentsOf: yLog, encoding: .utf8)).map { lastLines($0, 8) } ?? y.output
            throw Failure(message: "yosys failed (exit status \(y.status)): \(tail)")
        }
        let cells = yosysStat((try? String(contentsOf: yLog, encoding: .utf8)) ?? "")
        emit(.info, "yosys mapped \(e) to \(cells.reduce(0) { $0 + $1.count }) cells in \(String(format: "%.1f", y.elapsed)) s",
             cells.map { Message(level: .info, text: "\($0.count) \($0.type)") })

        // 2. Place and route (nextpnr-mistral).
        let pinName = Dictionary(fit.io.map { ($0.location, $0.name) }, uniquingKeysWith: { a, _ in a })
        emit(.info, "Running nextpnr-mistral --device \(config.device) --seed \(config.seed) (loads the full-device routing graph; uses about 1.7 GB of memory)")
        var ioCells: [PnRResult.IOCell] = []
        var util: [(String, Int, Int)] = []
        var inUtil = false
        let args = ["--device", config.device, "--json", jURL.lastPathComponent, "--qsf", qURL.lastPathComponent,
                    "--rbf", rbfURL.lastPathComponent, "--seed", "\(config.seed)", "--log", nLog.lastPathComponent,
                    "--report", repURL.lastPathComponent, "--write", routedURL.lastPathComponent]
        let n = try ToolProcess.run(tc.nextpnr.url, args, cwd: work, cancel: config.cancel) { line in
            if inUtil {
                if let u = parseUtilLine(line) { util.append(u); return }
                inUtil = false
                if !util.isEmpty {
                    emit(.info, "nextpnr-mistral device utilisation", util.filter { $0.1 > 0 }.map { Message(level: .info, text: "\($0.0): \($0.1) / \(CompileFlow.thousands($0.2))") })
                }
            }
            if let io = parseConstrain(line) {
                let name = pinName[io.pin] ?? io.cell
                ioCells.append(.init(name: name, pin: io.pin, bel: io.bel))
                emit(.info, "Pin \"\(name)\" placed at \(io.pin) (nextpnr I/O cell \(io.bel))")
                return
            }
            let t = line.trimmingCharacters(in: .whitespaces)
            if t.hasPrefix("Info: Device utilisation:") { inUtil = true; return }
            if t.hasPrefix("Warning:") { emit(.warning, "nextpnr-mistral: " + t.dropFirst(8).trimmingCharacters(in: .whitespaces)); return }
            if t.hasPrefix("ERROR:") { emit(.error, "nextpnr-mistral: " + t.dropFirst(6).trimmingCharacters(in: .whitespaces)); return }
            guard t.hasPrefix("Info:") else { return }
            let body = t.dropFirst(5).trimmingCharacters(in: .whitespaces)
            if body.hasPrefix("Running main analytical placer") { emit(.info, "Placement: HeAP analytic placer, then simulated annealing (nextpnr-mistral)") }
            else if body.hasPrefix("HeAP Placer Time:") { emit(.info, "Analytic placement finished (\(body))") }
            else if body.hasPrefix("SA placement time") { emit(.info, "Placement was successful (\(body))") }
            else if body.hasPrefix("Running router2") { emit(.info, "Routing: router2 (nextpnr-mistral)") }
            else if body.hasPrefix("iter=") { emit(.info, "Router iteration: \(body)") }
            else if body.hasPrefix("Router2 time") { emit(.info, "Routing was successful (\(body))") }
            else if body.hasPrefix("Program finished normally") { emit(.info, "nextpnr-mistral finished normally") }
        }
        if n.cancelled { throw Failure(message: "Processing was stopped by the user") }
        times.append(("nextpnr-mistral", n.elapsed))
        guard n.status == 0, fm.fileExists(atPath: rbfURL.path) else {
            let log = (try? String(contentsOf: nLog, encoding: .utf8)) ?? n.output
            let errs = log.split(separator: "\n").filter { $0.contains("ERROR") }.map(String.init)
            throw Failure(message: "nextpnr-mistral failed (exit status \(n.status)): " + (errs.isEmpty ? lastLines(log, 6) : errs.joined(separator: " | ")))
        }
        // Utilisation and placement from nextpnr's JSON outputs.
        if let d = try? Data(contentsOf: repURL), let j = try? JSONSerialization.jsonObject(with: d) as? [String: Any],
           let u = j["utilization"] as? [String: Any] {
            util = u.compactMap { k, v in
                guard let o = v as? [String: Any], let used = (o["used"] as? NSNumber)?.intValue, let av = (o["available"] as? NSNumber)?.intValue else { return nil }
                return (k, used, av)
            }.sorted { $0.0 < $1.0 }
        }
        var placed: [PnRResult.Cell] = []
        if let d = try? Data(contentsOf: routedURL), let j = try? JSONSerialization.jsonObject(with: d) as? [String: Any],
           let mods = j["modules"] as? [String: Any] {
            for (_, m) in mods {
                guard let cs = (m as? [String: Any])?["cells"] as? [String: Any] else { continue }
                for (name, c) in cs {
                    guard let c = c as? [String: Any] else { continue }
                    let attrs = c["attributes"] as? [String: Any] ?? [:]
                    placed.append(.init(name: name, type: c["type"] as? String ?? "?", bel: attrs["NEXTPNR_BEL"] as? String ?? "--"))
                }
            }
        }
        placed.sort { ($0.type, $0.bel) < ($1.type, $1.bel) }
        let rbfBytes = (try? fm.attributesOfItem(atPath: rbfURL.path)[.size] as? NSNumber)?.intValue ?? 0
        emit(.info, "nextpnr-mistral wrote \(rbfURL.lastPathComponent) (\(CompileFlow.thousands(rbfBytes)) bytes, raw uncompressed bitstream) in \(String(format: "%.1f", n.elapsed)) s")

        // 3. Decode the bitstream with mistral-cv (independent of nextpnr) for the report.
        let (bt, dt) = try decompile(rbfURL, to: btURL, config: config)
        times.append(("mistral-cv decomp", dt))
        let check = BitstreamVerifier.check(bt, spec: spec(circuit, fit: fit, synthesis: synthesis))
        emit(.info, "Decoded the bitstream with mistral-cv: \(check.routedLinks) routed links, \(check.settingsCount) non-default settings, \(check.configuredALMs) ALMs in \(check.configuredLABs) LABs configured",
             check.pins.map { Message(level: $0.ok ? .info : .warning, text: "Pin \"\($0.name)\" (\($0.isInput ? "input" : "output")) at PIN_\($0.pin): \($0.note)\($0.node == "--" ? "" : " [\($0.node)]")") })
        return PnRResult(workDirectory: work, verilogURL: vURL, qsfURL: qURL, netlistURL: jURL, rbfURL: rbfURL, btURL: btURL,
                         yosysLog: yLog, nextpnrLog: nLog, yosysVersion: yv, nextpnrVersion: nv, mistralVersion: mv,
                         yosysCells: cells, utilization: util, ioCells: ioCells, cells: placed, rbfBytes: rbfBytes,
                         check: check, times: times)
    }

    static func decompile(_ rbf: URL, to bt: URL, config: HardwareConfig) throws -> (DecodedBitstream, TimeInterval) {
        try? FileManager.default.removeItem(at: bt)
        let r = try ToolProcess.run(config.toolchain.mistralCV.url, ["decomp", config.device, rbf.path, bt.path], cancel: config.cancel)
        if r.cancelled { throw Failure(message: "Processing was stopped by the user") }
        guard r.status == 0, let text = try? String(contentsOf: bt, encoding: .utf8) else {
            throw Failure(message: "mistral-cv decomp failed (exit status \(r.status)): \(lastLines(r.output, 6))")
        }
        return (try DecodedBitstream(text: text), r.elapsed)
    }

    // MARK: - Assembler

    static func assemble(project p: Project, circuit: CompiledCircuit, synthesis: SynthesisResult?, fit: FitResult, pnr: PnRResult,
                         config: HardwareConfig, emit: Emitter) throws -> AssemblyResult {
        let fm = FileManager.default
        let e = p.entityName
        let sofURL = config.sofFile(e)
        try fm.createDirectory(at: sofURL.deletingLastPathComponent(), withIntermediateDirectories: true)
        if config.protectForeignSOF && fm.fileExists(atPath: sofURL.path) && !isQuartziteSOF(sofURL) {
            throw Failure(message: "\(sofURL.path) already exists and was not written by Quartzite (it may be a Quartus .sof). Quartzite does not overwrite it; move or rename it and run the Assembler again")
        }
        let rbf = try Data(contentsOf: pnr.rbfURL)
        var opt = SOFFile.WrapOptions()
        opt.layout = config.sofLayout
        opt.projectName = e
        let sof = try SOFFile(wrapping: rbf, device: config.device, options: opt)
        let bytes = sof.serialize()
        // Write next to the target first; only a verified file takes the real name.
        let pending = pnr.workDirectory.appendingPathComponent("\(e)_unverified.sof")
        try? fm.removeItem(at: pending)
        try bytes.write(to: pending, options: .atomic)
        emit(.info, "Wrote \(pending.lastPathComponent) (\(CompileFlow.thousands(bytes.count)) bytes, \(sof.records.count) records, layout \(config.sofLayout == 17 ? "of Quartus 17.0 and later, including 18.1" : "\(config.sofLayout)"))")

        // Read the file back as a programmer would and check its own checksums.
        let back = try SOFFile(contentsOf: pending)
        var problems: [String] = []
        let crc = back.storedCRC ?? 0
        if back.computedCRC() != crc { problems.append("file CRC-16 does not match") }
        let sum = back.computedChecksum() ?? 0
        if back.storedChecksum != sum { problems.append("checksum record does not match the payload") }
        if back.device != config.device { problems.append("device record is \(back.device ?? "missing")") }
        if config.sofLayout == 17 && back.records.count != 11 { problems.append("\(back.records.count) records instead of 11") }
        emit(.info, "Read the .sof back: device \(back.device ?? "?"), checksum \(hex32(sum)), file CRC-16 \(String(format: "0x%04X", crc))" + (problems.isEmpty ? " (both match)" : ""))

        // Re-extract the bitstream from the file and compare every configuration bit.
        let extracted = try back.extractRBF()
        let exURL = pnr.workDirectory.appendingPathComponent("\(e)_from_sof.rbf")
        try extracted.write(to: exURL, options: .atomic)
        // `sof` holds nextpnr's configuration exactly as parsed from its .rbf.
        let b = try CycloneVConfig(rbf: extracted)
        let same = sof.cram?.data == b.cram && sof.pram?.data == b.pram && back.cram?.data == b.cram
        emit(same ? .info : .error, same
             ? "Re-extracted the bitstream from the .sof: all \(CompileFlow.thousands(CycloneVSX120F.cramSX * CycloneVSX120F.cramSY)) CRAM bits and \(CompileFlow.thousands(CycloneVSX120F.pramBits)) PRAM bits equal nextpnr's bitstream"
             : "The bitstream re-extracted from the .sof differs from nextpnr's bitstream")
        if !same { problems.append("re-extracted bitstream differs from nextpnr's") }

        // Decode it with mistral-cv and check every pin and the whole truth table.
        let btURL = pnr.workDirectory.appendingPathComponent("\(e)_from_sof.bt")
        let (bt, _) = try decompile(exURL, to: btURL, config: config)
        let check = BitstreamVerifier.check(bt, spec: spec(circuit, fit: fit, synthesis: synthesis))
        for pin in check.pins {
            emit(pin.ok ? .info : .error, "Bitstream check: \(pin.isInput ? "input" : "output") \"\(pin.name)\" at PIN_\(pin.pin): \(pin.note)")
        }
        if !check.strayDrivenPins.isEmpty {
            emit(.error, "Bitstream check: output drivers are enabled on pins that are not design outputs: \(check.strayDrivenPins.joined(separator: ", "))")
        }
        if let err = check.evaluationError {
            emit(.error, "Bitstream check: the routed netlist could not be evaluated: \(err)")
        } else {
            let kids = check.outputNames.enumerated().map { Message(level: check.outputRowsCorrect[$0.offset] == check.rows ? .info : .error,
                                                                    text: "\($0.element): \(check.outputRowsCorrect[$0.offset])/\(check.rows) rows") }
                + check.mismatches.map { Message(level: .error, text: $0) }
            emit(check.rowsMatching == check.rows ? .info : .error,
                 "Bitstream check: \(check.rowsMatching)/\(check.rows) truth-table rows of the decoded bitstream match the schematic simulation", kids)
        }
        problems += check.failures

        var failure: String? = nil
        if problems.isEmpty {
            try? fm.removeItem(at: sofURL)
            try fm.moveItem(at: pending, to: sofURL)
            try? marker(for: sofURL, checksum: sum, bytes: bytes.count).write(to: markerURL(sofURL), atomically: true, encoding: .utf8)
            emit(.info, "Generated programming file \(sofURL.path) (checksum \(hex32(sum)))")
            emit(.warning, experimentalNotice)
        } else {
            failure = problems.joined(separator: "; ")
            emit(.error, "The .sof failed verification and was not written to \(sofURL.lastPathComponent). The unverified file is kept for inspection at \(pending.path)")
        }
        return AssemblyResult(sofURL: problems.isEmpty ? sofURL : pending, bytes: bytes.count, checksum: sum, crc: crc,
                              records: back.records.count, layout: config.sofLayout,
                              compilerVersionRecord: back.compilerVersion ?? "", extractedRBF: exURL, btURL: btURL,
                              roundTripIdentical: same, check: check, failure: failure)
    }

    // MARK: - Checking a .sof from another tool

    /// Checks a .sof compiled elsewhere (Quartus, from the exported project) against the schematic
    /// with the Assembler's decoder and checks. Quartus folds unrouted LUT inputs into its masks as
    /// 1, so they are assumed to read 1 (QZ_FLOAT_INPUT overrides).
    static func verifyForeignSOF(project p: Project, sof url: URL, config: HardwareConfig) throws -> BitstreamCheck {
        let state = CompileFlow.run(p, stages: [.analysisSynthesis, .fitter])
        guard !state.failed, let circuit = state.circuit, let fit = state.fit else {
            throw Failure(message: "the schematic does not compile" + (state.messages.first { $0.level == .error }.map { ": \($0.text)" } ?? ""))
        }
        let unplaced = fit.io.filter { !$0.assignedByUser }.map { $0.name }
        guard unplaced.isEmpty else {
            throw Failure(message: "no location assignment for \(unplaced.joined(separator: ", ")); the check needs the pins the .sof was compiled with")
        }
        let sof = try SOFFile(contentsOf: url)
        try sof.validate()
        guard let dev = CycloneVSX120F.part(sof.device ?? ""), dev == CycloneVSX120F.part(p.device) else {
            throw Failure(message: "the .sof is for \(sof.device ?? "an unknown device"), the project for \(p.device)")
        }
        let work = config.workDir(p.entityName)
        try FileManager.default.createDirectory(at: work, withIntermediateDirectories: true)
        let base = url.deletingPathExtension().lastPathComponent
        let rbfURL = work.appendingPathComponent("\(base)_from_sof.rbf")
        try sof.extractRBF().write(to: rbfURL, options: .atomic)
        var c = config
        c.device = dev
        let (bt, _) = try decompile(rbfURL, to: work.appendingPathComponent("\(base)_from_sof.bt"), config: c)
        var s = spec(circuit, fit: fit, synthesis: state.synthesis)
        s.unroutedInputsRead = 1
        return BitstreamVerifier.check(bt, spec: s)
    }

    // MARK: - Marker file next to a Quartzite .sof

    static func markerURL(_ sof: URL) -> URL { sof.deletingLastPathComponent().appendingPathComponent(sof.lastPathComponent + ".quartzite.txt") }

    static func marker(for sof: URL, checksum: UInt32, bytes: Int) -> String {
        """
        \(sof.lastPathComponent) was generated by Quartzite for Mac (open-source yosys + nextpnr-mistral + Mistral flow).
        It was NOT generated by Intel Quartus Prime and has NOT yet been tested on hardware.
        Try it first on a trivial design (for example f = w AND x) and keep compiling in Quartus for graded work.
        If configuration fails, program a .sof made by Quartus instead; nothing is stored on the board permanently.

        checksum: \(hex32(checksum))
        size: \(bytes) bytes

        """
    }

    /// True if `url` is a .sof Quartzite wrote (its marker file names the same checksum).
    static func isQuartziteSOF(_ url: URL) -> Bool {
        guard let text = try? String(contentsOf: markerURL(url), encoding: .utf8),
              let sof = try? SOFFile(contentsOf: url), let sum = sof.storedChecksum else { return false }
        return text.contains("checksum: \(hex32(sum))")
    }

    // MARK: - Parsing helpers

    static func lastLines(_ s: String, _ n: Int) -> String {
        s.split(separator: "\n").suffix(n).map { $0.trimmingCharacters(in: .whitespaces) }.joined(separator: " | ")
    }

    /// Cells from the last `stat` section of a yosys log.
    static func yosysStat(_ log: String) -> [(type: String, count: Int)] {
        guard let r = log.range(of: "Printing statistics", options: .backwards) else { return [] }
        var out: [(String, Int)] = []
        for line in log[r.upperBound...].split(separator: "\n") {
            let parts = line.split(separator: " ", omittingEmptySubsequences: true)
            if parts.count == 2, let c = Int(parts[0]), parts[1].hasPrefix("MISTRAL_") || parts[1].hasPrefix("$") {
                if !out.contains(where: { $0.0 == String(parts[1]) }) { out.append((String(parts[1]), c)) }
            }
        }
        return out.sorted { $0.0 < $1.0 }
    }

    /// "Info: Constraining IO 'x' to pin PIN_AB28 (bel MISTRAL_IO.89.21.2)"
    static func parseConstrain(_ line: String) -> (cell: String, pin: String, bel: String)? {
        guard let a = line.range(of: "Constraining IO '"), let b = line.range(of: "' to pin ", range: a.upperBound..<line.endIndex),
              let c = line.range(of: " (bel ", range: b.upperBound..<line.endIndex), let d = line.range(of: ")", range: c.upperBound..<line.endIndex) else { return nil }
        return (String(line[a.upperBound..<b.lowerBound]), String(line[b.upperBound..<c.lowerBound]), String(line[c.upperBound..<d.lowerBound]))
    }

    /// "Info: \t        MISTRAL_COMB:       3/  83820     0%"
    static func parseUtilLine(_ line: String) -> (String, Int, Int)? {
        guard line.hasPrefix("Info:") else { return nil }
        let body = line.dropFirst(5).trimmingCharacters(in: .whitespaces)
        guard let colon = body.firstIndex(of: ":") else { return nil }
        let name = String(body[..<colon])
        let rest = body[body.index(after: colon)...].replacingOccurrences(of: "%", with: "")
        let nums = rest.split(whereSeparator: { $0 == "/" || $0 == " " }).compactMap { Int($0) }
        guard nums.count >= 2, !name.contains(" ") else { return nil }
        return (name, nums[0], nums[1])
    }

    /// "MISTRAL_COMB.88.21.0" -> "LAB X88 Y21 (site 0)"; "MISTRAL_IO.89.25.3" -> "I/O X89 Y25 (site 3)".
    static func belLabel(_ bel: String) -> String {
        let p = bel.split(separator: ".")
        guard p.count == 4 else { return bel }
        let kind: String
        switch p[0] {
        case "MISTRAL_COMB": kind = "LAB"
        case "MISTRAL_MCOMB": kind = "MLAB"
        case "MISTRAL_IO": kind = "I/O"
        case "MISTRAL_FF": kind = "LAB FF"
        default: kind = String(p[0])
        }
        return "\(kind) X\(p[1]) Y\(p[2]) (site \(p[3]))"
    }
