import Foundation

/// Quartzite EDA Netlist Writer: a structural, LUT-level Verilog netlist of the synthesized
/// design, laid out like the `.vo` file Quartus writes for ModelSim but using a small
/// behavioural LUT model (`qz_lcell_comb`) so it simulates in any Verilog simulator without
/// Intel's libraries. It is clearly marked as Quartzite output.
enum NetlistWriter {
    static let folder = "simulation/quartzite"
    static func fileName(_ entity: String) -> String { "\(entity)_quartzite.vo" }
    static func path(_ entity: String) -> String { "\(folder)/\(fileName(entity))" }

    /// The netlist file for an export bundle (path relative to the project folder), or nil
    /// if the design does not compile.
    static func bundleFile(_ p: Project, date: Date = Date()) -> (name: String, contents: String)? {
        let state = CompileFlow.run(p, stages: [.analysisSynthesis, .fitter, .eda], mainTask: "EDA Netlist Writer")
        guard let text = state.netlist else { return nil }
        return (path(p.entityName), text)
    }

    static func quartusDate(_ d: Date) -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "MM/dd/yyyy HH:mm:ss"
        return f.string(from: d)
    }

    static func verilog(_ s: SynthesisResult, fit: FitResult?, project: Project, date: Date = Date()) -> String {
        let e = project.entityName
        let net = s.network
        let pinNames = Set(net.inputNames + net.outputNames)
        func wire(_ i: Int) -> String {
            var n = "qz_lut_\(i)"
            while pinNames.contains(n) { n += "_" }
            return n
        }
        let cellType = e == "qz_lcell_comb" ? "qz_lcell_comb_model" : "qz_lcell_comb"
        let usedNames = pinNames.union(net.luts.indices.map(wire))
        func cell(_ i: Int) -> String {
            var name = "qz_cell_\(i)"
            while usedNames.contains(name) { name += "_" }
            return name
        }
        func sig(_ x: LUTNetwork.Signal) -> String {
            switch x {
            case .constant(let v): return v ? "1'b1" : "1'b0"
            case .input(let k): return net.inputNames[k]
            case .lut(let i): return wire(i)
            }
        }
        var out = """
        // Quartzite EDA Netlist Writer
        // This file was generated by Quartzite for Mac. It was NOT generated by Intel Quartus Prime.
        //
        // Functional (zero-delay) LUT-level netlist of "\(e)" after Quartzite Analysis & Synthesis
        // and Fitter, for simulation only. Each qz_lcell_comb models one Cyclone V
        // cyclonev_lcell_comb in normal mode. lut_mask uses the bit order Quartus uses:
        // bit index = dataf*32 + datae*16 + datad*8 + datac*4 + datab*2 + dataa.
        // Placement comments use Quartzite's logical LAB numbering, not Quartus coordinates.
        //
        // DATE "\(quartusDate(date))"
        // Device: \(project.device) (Cyclone V SX, \(CycloneV.package)) on the Terasic DE10-Standard

        `timescale 1 ps/ 1 ps


        """
        let ports = net.outputNames + net.inputNames
        out += "module \(e) (\n" + ports.map { "\t\($0)" }.joined(separator: ",\n") + ");\n"
        for o in net.outputNames { out += "output \t\(o);\n" }
        for i in net.inputNames { out += "input \t\(i);\n" }
        out += "\n// Design Ports Information\n"
        if let fit {
            for io in fit.io {
                var line = "// \(io.name)\t=>  Location: \(io.location),\t I/O Bank: \(io.bank ?? "--")"
                if let b = io.board { line += ",\t Board: \(b.longLabel)" }
                if !io.assignedByUser { line += ",\t placed by the Quartzite Fitter (no location assignment)" }
                out += line + "\n"
            }
        }
        out += "\n"
        if !net.luts.isEmpty { out += "wire " + net.luts.indices.map(wire).joined(separator: ", ") + ";\n\n" }
        let place = Dictionary(uniqueKeysWithValues: (fit?.logic ?? []).map { ($0.lut, $0) })
        for (i, l) in net.luts.enumerated() {
            out += "// Node: \(l.name)\n"
            if let p = place[i] { out += "// Location: Quartzite \(p.location)\n" }
            out += "// Equation(s):\n// \(l.name) = \(net.equation(i))\n\n"
            out += "\(cellType) #(.lut_mask(\(LUTMask.hex(l.mask)))) \(cell(i)) (\n"
            for (k, port) in LUTNetwork.LUT.ports.enumerated() {
                out += "\t.\(port)(\(k < l.inputs.count ? sig(l.inputs[k]) : "1'b0")),\n"
            }
            out += "\t.combout(\(wire(i))));\n\n"
        }
        for (o, name) in net.outputNames.enumerated() {
            out += "assign \(name) = \(sig(net.outputs[o]));\n"
        }
        out += """

        endmodule

        // Behavioural model of one Cyclone V LUT (normal mode), so this file runs in any
        // Verilog simulator. Not an Intel library cell.
        module \(cellType) (dataa, datab, datac, datad, datae, dataf, combout);
        \tparameter [63:0] lut_mask = 64'h0000000000000000;
        \tinput dataa, datab, datac, datad, datae, dataf;
        \toutput combout;
        \tassign combout = lut_mask[{dataf, datae, datad, datac, datab, dataa}];
        endmodule

        """
        return out
    }

    /// Minimal reader for the netlists written above, used by the self-test to check the
    /// text itself (not just the in-memory network). Returns nil if the text doesn't parse.
    static func simulate(_ text: String, inputs: [String: Bool]) -> [String: Bool]? {
        guard let cellRegex = try? NSRegularExpression(pattern: "qz_lcell_comb(?:_model)? #\\(\\.lut_mask\\(64'h([0-9A-F]{16})\\)\\) \\w+ \\(([^;]*)\\);"),
              let portRegex = try? NSRegularExpression(pattern: "\\.(\\w+)\\(([^)]*)\\)"),
              let assignRegex = try? NSRegularExpression(pattern: "(?m)^assign (\\w+) = ([^;]+);") else { return nil }
        var values = inputs
        func value(_ s: String) -> Bool? {
            let t = s.trimmingCharacters(in: .whitespaces)
            if t == "1'b0" { return false }
            if t == "1'b1" { return true }
            return values[t]
        }
        let ns = NSString(string: text)
        for m in cellRegex.matches(in: text, range: NSRange(location: 0, length: ns.length)) {
            guard let mask = UInt64(ns.substring(with: m.range(at: 1)), radix: 16) else { return nil }
            let body = ns.substring(with: m.range(at: 2))
            var conn: [String: String] = [:]
            let nb = NSString(string: body)
            for p in portRegex.matches(in: body, range: NSRange(location: 0, length: nb.length)) {
                conn[nb.substring(with: p.range(at: 1))] = nb.substring(with: p.range(at: 2))
            }
            var idx = 0
            for (k, port) in LUTNetwork.LUT.ports.enumerated() {
                guard let src = conn[port], let v = value(src) else { return nil }
                if v { idx |= 1 << k }
            }
            guard let outName = conn["combout"] else { return nil }
            values[outName] = (mask >> UInt64(idx)) & 1 == 1
        }
        var outs: [String: Bool] = [:]
        for m in assignRegex.matches(in: text, range: NSRange(location: 0, length: ns.length)) {
            let name = ns.substring(with: m.range(at: 1))
            guard let v = value(ns.substring(with: m.range(at: 2))) else { return nil }
            outs[name] = v
        }
        return outs
    }
}
